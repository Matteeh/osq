// Writes the CLI reference page from osq's own command definitions, so the docs
// list exactly the commands, arguments and options the CLI parses.
//
// It loads `createProgram` from ../src/cli with jiti, which needs the osq
// package's dependencies installed at the repository root. Without them it
// keeps the committed page and says so, so a docs-only build still works.

import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../..');
const out = resolve(here, '../src/content/docs/docs/reference/cli.md');

let cli;
let groupsModule;
let slicesModule;
try {
  const { createJiti } = await import('jiti');
  const jiti = createJiti(import.meta.url);
  cli = await jiti.import(resolve(root, 'src/cli/index.ts'));
  groupsModule = await jiti.import(resolve(root, 'src/cli/help-groups.ts'));
  slicesModule = await jiti.import(resolve(root, 'src/cli/slices.ts'));
} catch (error) {
  console.warn(`cli-reference: kept the committed page, could not load the CLI (${error.message.split('\n')[0]})`);
  console.warn('cli-reference: run pnpm install at the repository root to regenerate it');
  process.exit(0);
}

const program = cli.createProgram(cli.resolvePackageVersion());
const groups = groupsModule.commandGroups(slicesModule.SLICES);

/** Markdown-safe table cell. */
const cell = (text) => text.replace(/\|/g, '\\|').replace(/\n+/g, ' ');
/** Sentence case for commander's lowercase descriptions. */
const sentence = (text) => (text ? `${text[0].toUpperCase()}${text.slice(1)}${/[.!?]$/.test(text) ? '' : '.'}` : '');

/** One section per command, then one per subcommand under it. */
function section(command, path) {
  const help = command.createHelp();
  const name = [...path, command.name()].join(' ');
  const usage = help.commandUsage(command);
  const lines = [`### ${name}`, '', sentence(command.description()), '', '```sh', usage, '```', ''];

  const args = help.visibleArguments(command);
  if (args.length > 0) {
    lines.push('| Argument | Description |', '| --- | --- |');
    for (const arg of args) lines.push(`| \`${help.argumentTerm(arg)}\` | ${cell(sentence(help.argumentDescription(arg))) || ' '} |`);
    lines.push('');
  }

  const options = help.visibleOptions(command).filter((option) => option.long !== '--help');
  if (options.length > 0) {
    lines.push('| Option | Description |', '| --- | --- |');
    for (const option of options) lines.push(`| \`${cell(help.optionTerm(option))}\` | ${cell(sentence(help.optionDescription(option)))} |`);
    lines.push('');
  }

  for (const sub of command.commands) lines.push(...section(sub, [...path, command.name()]));
  return lines;
}

const byName = new Map(program.commands.map((command) => [command.name(), command]));
const rootHelp = program.createHelp();
const rootOptions = rootHelp
  .visibleOptions(program)
  .filter((option) => option.long !== '--help')
  .map((option) => `| \`${cell(rootHelp.optionTerm(option))}\` | ${cell(sentence(rootHelp.optionDescription(option)))} |`);

const page = [
  '---',
  'title: CLI reference',
  `description: Every osq command, argument and option in osq ${program.version()}.`,
  '---',
  '',
  '<!-- Generated by docs/scripts/cli-reference.mjs from src/cli. Edit the command definitions, not this file. -->',
  '',
  `This page is generated from the command definitions in osq ${program.version()}, so it matches what the CLI accepts. \`osq <command> --help\` prints the same information in your terminal.`,
  '',
  '## osq',
  '',
  'Run with no command, osq prints the inbox: what needs you, what is running and what landed since you last looked.',
  '',
  '```sh',
  'osq [options] [command]',
  '```',
  '',
  '| Option | Description |',
  '| --- | --- |',
  ...rootOptions,
  '',
];

const listed = new Set();
for (const group of groups) {
  const commands = group.commands.map((name) => byName.get(name)).filter(Boolean);
  if (commands.length === 0) continue;
  page.push(`## ${group.title}`, '');
  for (const command of commands) {
    listed.add(command.name());
    page.push(...section(command, ['osq']));
  }
}
const rest = program.commands.filter((command) => !listed.has(command.name()));
if (rest.length > 0) {
  page.push('## Other', '');
  for (const command of rest) page.push(...section(command, ['osq']));
}

writeFileSync(out, `${page.join('\n').replace(/\n+$/, '')}\n`);
console.log(`cli-reference: wrote ${program.commands.length} commands to ${out.slice(root.length + 1)}`);
