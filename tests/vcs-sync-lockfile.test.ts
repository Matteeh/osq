import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { afterEach, describe, it } from 'node:test';
import { promisify } from 'node:util';
import { DEFAULT_CONFIG, type OsqConfig } from '../src/core/foundation/config.js';
import { type LocatedChange, listChanges } from '../src/core/status/change-locations.js';
import { syncWithDefaultBranch } from '../src/core/vcs/sync-main.js';
import { SyncStop } from '../src/core/vcs/sync-stop.js';

const execFileAsync = promisify(execFile);
const GIT_AUTHOR = 'Osq Author <author@example.invalid>';
const FOLDER = '002-two-words';
const BRANCH = `osq/${FOLDER}`;
const WORKSPACE = '[workspace]\nmembers = ["crates/*"]\nresolver = "2"\n';
const PROPOSAL = `---
title: Two words
---

## Goal

Do two words.
`;

const tmpDirs: string[] = [];

afterEach(async () => {
  for (const dir of tmpDirs.splice(0)) {
    await fs.rm(dir, { recursive: true, force: true });
  }
});

/** The git calls ignore redirecting variables, like osq's own reads. */
function cleanGitEnv(): NodeJS.ProcessEnv {
  const env = { ...process.env };
  for (const key of ['GIT_DIR', 'GIT_INDEX_FILE', 'GIT_WORK_TREE']) {
    Reflect.deleteProperty(env, key);
  }
  return env;
}

async function git(args: string[], cwd: string): Promise<string> {
  const { stdout } = await execFileAsync('git', args, { cwd, env: cleanGitEnv() });
  return stdout.trim();
}

async function cargo(cwd: string, args: string[]): Promise<void> {
  await execFileAsync('cargo', args, { cwd, env: cleanGitEnv() });
}

async function write(root: string, relative: string, content: string): Promise<void> {
  const target = path.join(root, relative);
  await fs.mkdir(path.dirname(target), { recursive: true });
  await fs.writeFile(target, content, 'utf8');
}

async function headOf(dir: string): Promise<string> {
  return git(['rev-parse', 'HEAD'], dir);
}

async function statusOf(dir: string): Promise<string> {
  return git(['status', '--porcelain'], dir);
}

/** A workspace crate with no registry dependency, or the given `[dependencies]` block. */
async function writeCrate(root: string, name: string, dependencies = ''): Promise<void> {
  await write(
    root,
    `crates/${name}/Cargo.toml`,
    `[package]\nname = "${name}"\nversion = "0.1.0"\nedition = "2021"\n${dependencies}`,
  );
  await write(root, `crates/${name}/src/lib.rs`, 'pub fn marker() {}\n');
}

/** A hand-written lock file naming `names` in the given order. */
function lockText(names: readonly string[]): string {
  const blocks = names
    .map((name) => `[[package]]\nname = "${name}"\nversion = "0.1.0"`)
    .join('\n\n');
  return `# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n${blocks}\n`;
}

function configFor(parent: string): OsqConfig {
  return {
    ...DEFAULT_CONFIG,
    vcs: {
      enabled: true,
      author: GIT_AUTHOR,
      worktreeRoot: path.join(parent, 'worktrees'),
    },
  };
}

/** A repository on `main` with a Cargo workspace of `a` and `z`, plus `src/app.txt`. */
async function initRepo(): Promise<{ parent: string; root: string; base: string }> {
  const parent = await fs.mkdtemp(path.join(os.tmpdir(), 'osq-vcssynclock-'));
  tmpDirs.push(parent);
  const root = path.join(parent, 'repo');
  await fs.mkdir(root);
  await git(['init', '-q', '-b', 'main'], root);
  await git(['config', 'user.name', 'osq'], root);
  await git(['config', 'user.email', 'osq@example.invalid'], root);
  await write(root, 'Cargo.toml', WORKSPACE);
  await writeCrate(root, 'a');
  await writeCrate(root, 'z');
  await write(root, 'src/app.txt', 'base\n');
  await cargo(root, ['generate-lockfile', '--offline']);
  await git(['add', '-A'], root);
  await git(['commit', '-qm', 'init'], root);
  return { parent, root, base: await git(['rev-parse', 'HEAD'], root) };
}

interface BranchOptions {
  readonly crateDependencies?: string;
  readonly lockText?: string;
  readonly appLine?: string;
}

/** Add an active `002` on `osq/002-two-words`, with crate `m2` and a lock file. */
async function addActive002(
  root: string,
  parent: string,
  base: string,
  options: BranchOptions,
): Promise<string> {
  await git(['branch', BRANCH], root);
  const worktree = path.join(parent, 'wt002');
  await git(['worktree', 'add', worktree, BRANCH], root);
  const folder = `openspec/changes/${FOLDER}`;
  await write(worktree, `${folder}/proposal.md`, PROPOSAL);
  await write(worktree, `${folder}/.run/approved`, 'approved\n');
  await write(worktree, `${folder}/.run/base`, `${base}\n`);
  await writeCrate(worktree, 'm2', options.crateDependencies ?? '');
  if (options.lockText !== undefined) {
    await write(worktree, 'Cargo.lock', options.lockText);
  } else {
    await cargo(worktree, ['generate-lockfile', '--offline']);
  }
  if (options.appLine !== undefined) await write(worktree, 'src/app.txt', options.appLine);
  await git(['add', '-A'], worktree);
  await git(['commit', '-qm', 'active 002'], worktree);
  return worktree;
}

/** Add crate `m1` and its lock file to the default branch. */
async function landM1(root: string, options: BranchOptions): Promise<void> {
  await writeCrate(root, 'm1');
  if (options.lockText !== undefined) {
    await write(root, 'Cargo.lock', options.lockText);
  } else {
    await cargo(root, ['generate-lockfile', '--offline']);
  }
  if (options.appLine !== undefined) await write(root, 'src/app.txt', options.appLine);
  await git(['add', '-A'], root);
  await git(['commit', '-qm', 'land m1'], root);
}

async function findActive(root: string, config: OsqConfig): Promise<LocatedChange> {
  const found = (await listChanges(root, config, ['active'])).find(
    (change) => change.folderName === FOLDER,
  );
  assert.ok(found, 'the active change should be located in its worktree');
  return found;
}

describe('Default branch sync', () => {
  it('Both add a crate to one Cargo workspace', async () => {
    const { parent, root, base } = await initRepo();
    const config = configFor(parent);
    const worktree = await addActive002(root, parent, base, {});
    await landM1(root, {});
    const change = await findActive(root, config);

    const result = await syncWithDefaultBranch(root, config, change);

    assert.deepEqual(result, { merged: true });
    assert.equal(await git(['log', '-1', '--format=%s'], worktree), 'osq: 002 sync main');
    const lock = await fs.readFile(path.join(worktree, 'Cargo.lock'), 'utf8');
    assert.match(lock, /name = "m1"/);
    assert.match(lock, /name = "m2"/);
    assert.ok(!lock.includes('<<<<<<<'), 'the rebuilt lock file should hold no conflict marker');
    await cargo(worktree, ['metadata', '--offline', '--locked', '--format-version', '1']);
  });

  it('Lock file and code conflict', async () => {
    const { parent, root, base } = await initRepo();
    const config = configFor(parent);
    const worktree = await addActive002(root, parent, base, { appLine: 'branch\n' });
    await landM1(root, { appLine: 'main\n' });
    const beforeHead = await headOf(worktree);
    const beforeStatus = await statusOf(worktree);
    const change = await findActive(root, config);

    await assert.rejects(
      () => syncWithDefaultBranch(root, config, change),
      (error: unknown) => {
        assert.ok(error instanceof SyncStop, 'the stop should be a SyncStop');
        assert.equal(error.reason, 'sync_conflict');
        assert.match(error.message, /src\/app\.txt/);
        assert.doesNotMatch(error.message, /Cargo\.lock/);
        return true;
      },
    );
    assert.equal(await headOf(worktree), beforeHead);
    assert.equal(await statusOf(worktree), beforeStatus);
  });

  it('Lock file that cannot be rebuilt', async () => {
    const { parent, root, base } = await initRepo();
    const config = configFor(parent);
    const worktree = await addActive002(root, parent, base, {
      crateDependencies: '\n[dependencies]\nosq-no-such-crate = "1"\n',
      lockText: lockText(['a', 'm2', 'z']),
    });
    await landM1(root, { lockText: lockText(['a', 'm1', 'z']) });
    const beforeHead = await headOf(worktree);
    const beforeStatus = await statusOf(worktree);
    const change = await findActive(root, config);

    await assert.rejects(
      () => syncWithDefaultBranch(root, config, change),
      (error: unknown) => {
        assert.ok(error instanceof SyncStop, 'the stop should be a SyncStop');
        assert.equal(error.reason, 'sync_failed');
        assert.match(
          error.message,
          /^002-two-words: rebuilding Cargo\.lock failed on osq\/002-two-words merged with main:/,
        );
        return true;
      },
    );
    assert.equal(await headOf(worktree), beforeHead);
    assert.equal(await statusOf(worktree), beforeStatus);
  });
});
